  wire [9:0] kk  = dyo + {1'b0, adx[9:1]};
  wire plane = flying && in_map && (
                 (adx <= 10'd1 && dyo >= 10'd9 && dyo <= 10'd22) ||
                 (adx == 10'd0 && dyo == 10'd23) ||
                 (adx <= 10'd7 && kk >= 10'd15 && kk <= 10'd17) ||
