  // ================================================================ LOGO
  wire [9:0] u = pix_x - LX, v = pix_y - LY;
  wire after = (pix_x >= LX) && (pix_y >= LY);
  wire in_sq = after && (u < S) && (v < S);
  wire [9:0] lx = u - LBX, ly = v - LBY;
  wire in_lb = in_sq && (u >= LBX) && (u < LBX + LBW) && (v >= LBY) && (v < LBY + LBH);
  wire [1:0] a_raw = in_lb ? lrow[{lx, 1'b0} +: 2] : 2'd0;
  wire [9:0] reveal = {intro, 3'b0};
  wire [1:0] alpha  = (lx < reveal) ? a_raw : 2'd0;
  wire       pen    = (intro != 7'd50) && (a_raw != 0) && (lx < reveal) && (lx + 10'd12 >= reveal);
  wire [10:0] sd    = {1'b0, loopf, 2'b0} - ({1'b0, lx} + {1'b0, ly});
  wire       shine  = (intro == 7'd50) && (sd < 11'd26);

  // sombra larga: ROM dentro del cuadrado y proyección a 45° fuera de él
  wire        use_r = (u >= S) && ((v < S) || (u >= v));
  wire [10:0] vproj = {1'b0, v} + {1'b0, S} - 11'd1 - {1'b0, u};
  wire [10:0] uproj = {1'b0, u} + {1'b0, S} - 11'd1 - {1'b0, v};
  wire sh_out = use_r ? (({1'b0, v} + {1'b0, S} > {1'b0, u}) && SH_RIGHT[vproj[8:2]])
                      : (({1'b0, u} + {1'b0, S} > {1'b0, v}) && SH_BOTTOM[uproj[8:2]]);
  wire shadow = after && (in_sq ? srow[u[8:2]] : sh_out);

  // ================================================================ TEXTOS
  // línea 1, con ola
  localparam [9:0] TX1 = 10'd24, TY1 = 10'd352;
  wire [9:0] c1  = pix_x - TX1;
  wire [4:0] w1  = triw(c1[8:3] + {frame[3:0], 2'b0});
  wire [9:0] r1  = pix_y - TY1 - {7'b0, w1[4:2]};
  wire [9:0] c1s = c1 - 10'd2, r1s = r1 - 10'd2;
  wire [27:0] col1  = line1(c1[10-1:0]);
  wire [27:0] col1s = line1(c1s[10-1:0]);
  wire t1  = (pix_x >= TX1) && (c1  < LINE1_W) && (r1  < 10'd28) && col1[r1[4:0]];
  wire t1s = (pix_x >= TX1 + 10'd2) && (c1s < LINE1_W) && (r1s < 10'd28) && col1s[r1s[4:0]];
  // línea 2: ¡La UNL es TOP! · UNL en el mundo
  localparam [9:0] TX2 = 10'd200 - LINE2_W[10:1], TY2 = 10'd397;
  wire [9:0] c2 = pix_x - TX2, r2 = pix_y - TY2;
  wire [2*LINE2_H-1:0] col2 = line2(c2);
  wire [1:0] t2 = ((pix_x >= TX2) && (c2 < LINE2_W) && (r2 < LINE2_H)) ? col2[{r2[4:0], 1'b0} +: 2] : 2'd0;

  // cinta inferior
  wire [10:0] tcol_r = {1'b0, pix_x} + tk_off;
  wire [10:0] tcol   = (tcol_r >= TICKER_W) ? tcol_r - TICKER_W : tcol_r;
