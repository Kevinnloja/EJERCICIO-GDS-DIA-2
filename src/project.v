  // ================================================================ TIEMPO
  reg [10:0] frame;
  reg [6:0]  intro;                 // 0..50: el logo se "escribe"
  reg [10:0] tk_off;                // desplazamiento de la cinta
  wire [10:0] tk_next = tk_off + 11'd3;
  always @(posedge clk)
    if (~rst_n) begin frame <= 0; intro <= 0; tk_off <= 0; end
    else if (pix_x == 10'd0 && pix_y == 10'd0) begin
      frame  <= frame + 11'd1;
      if (intro != 7'd50) intro <= intro + 7'd1;
      tk_off <= (tk_next >= TICKER_W) ? tk_next - TICKER_W : tk_next;
    end

  wire [7:0] loopf  = frame[7:0];             // ciclo de ~4.3 s
  wire       flying = ~loopf[7];
  wire [7:0] prog   = flying ? {loopf[6:0], 1'b1} : 8'd255;   // avión al doble de velocidad

  function [4:0] triw(input [5:0] p);          // onda triangular 0..31
    triw = p[5] ? ~p[4:0] : p[4:0];
