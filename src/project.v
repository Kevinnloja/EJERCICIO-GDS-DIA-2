  wire in_frm = (pix_x + 10'd3 >= PX0) && (pix_x < PX0 + PW + 10'd3) && (pix_y + 10'd3 >= PY0) && (pix_y < PY0 + PH + 10'd3);
  wire in_psh = (pix_x >= PX0 + 10'd4) && (pix_x < PX0 + PW + 10'd10) && (pix_y >= PY0 + 10'd4) && (pix_y < PY0 + PH + 10'd10);
  wire [8:0] mi = {1'b0, mx[7:1], 1'b0} + {2'b0, mx[7:1]};
