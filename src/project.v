  // ================================================================ GEOMETRÍA
  localparam [9:0] LX = 10'd10,  LY = 10'd6,  S = 10'd340;    // logo
  localparam [9:0] PX0 = 10'd400, PY0 = 10'd14, PW = 10'd228, PH = 10'd420;  // mapa

  // filas de ROM cargadas una vez por línea (borrado horizontal)
  wire [9:0] ny  = (pix_y == 10'd524) ? 10'd0 : pix_y + 10'd1;
  wire [9:0] nv  = ny - LY;
  wire [9:0] nlb = nv - LBY;
  wire [9:0] npy = ny - PY0;
  reg [2*LBW-1:0] lrow;
  reg [84:0]      srow;
  reg [341:0]     mrow;
  reg [24:0]      prow;
  always @(posedge clk)
    if (pix_x == 10'd700) begin
      lrow <= (nv >= LBY && nv < LBY + LBH) ? logo_row(nlb[8:0]) : 0;
      srow <= (nv < S) ? shadow_row(nv[8:2]) : 85'd0;
      mrow <= (npy < PH) ? map_row(npy[8:1]) : 342'd0;
      prow <= (npy < PH) ? path_row(npy[8:0]) : 25'd0;
