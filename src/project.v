    endcase
    if (shine && alpha != 0) begin vr = 7'd48; vg = 7'd40; vb = 7'd10; end
    if (pen) begin vr = 7'd48; vg = 7'd44; vb = 7'd0; end

    // textos
    if (t1s) begin vr = 7'd24; vg = 7'd3; vb = 7'd6; end
    if (t1)  begin vr = 7'd48; vg = 7'd48; vb = 7'd48; end
    if (t2 == 2'd1) begin vr = 7'd48; vg = 7'd42; vb = 7'd6; end
    if (t2 == 2'd2) begin vr = 7'd48; vg = 7'd48; vb = frame[2] ? 7'd48 : 7'd10; end   // "TOP!" destella

    // panel del mapa
    if (in_psh && !in_frm) begin vr = 7'd26; vg = 7'd5; vb = 7'd8; end
    if (in_frm && !in_map) begin vr = 7'd48; vg = 7'd44; vb = 7'd16; end
    if (in_map) begin
      vr = 7'd2; vg = 7'd4; vb = 7'd14;                                    // océano
      if (mx[4:0] == 0 || my[4:0] == 0) begin vg = 7'd8; vb = 7'd22; end   // retícula
      case (mc)
        3'd1: begin vr = 7'd8;  vg = 7'd6;  vb = 7'd16; end                // otros países
        3'd6: begin vr = 7'd16; vg = 7'd14; vb = 7'd30; end
        3'd2: begin vr = 7'd8;  vg = 7'd22; vb = 7'd34; end                // Panamá
        3'd4: begin vr = 7'd10; vg = 7'd46; vb = 7'd48; end
        3'd3: begin                                                         // Ecuador = bandera
          if (fy < ECU_YEL)      begin vr = 7'd40 + {4'b0, fb}; vg = 7'd34 + {4'b0, fb}; vb = 7'd0; end
          else if (fy < ECU_BLU) begin vr = 7'd0;  vg = 7'd10 + {4'b0, fb}; vb = 7'd24 + {4'b0, fb}; end
          else                   begin vr = 7'd38 + {4'b0, fb}; vg = 7'd3; vb = 7'd5; end
        end
        3'd5: begin vr = 7'd48; vg = 7'd46; vb = (!flying && loopf[2]) ? 7'd48 : 7'd24; end
        default: ;
      endcase
      if (trail) begin vr = 7'd48; vg = 7'd48; vb = 7'd40; end
      if (ring)  begin vr = 7'd48; vg = 7'd46; vb = 7'd20; end
      if (loja_glow) begin vr = 7'd48; vg = 7'd36; vb = 7'd10; end
      if (loja_dot)  begin vr = 7'd48; vg = 7'd48; vb = 7'd48; end
      if (pin_gnd)   begin vr = 7'd0;  vg = 7'd0;  vb = 7'd4;  end
      if (pin_tip || pin_head) begin vr = 7'd46; vg = 7'd6; vb = 7'd10; end
      if (pin_hole)  begin vr = 7'd48; vg = 7'd48; vb = 7'd48; end
      if (lb == 2'd1) begin vr = 7'd0;  vg = 7'd0;  vb = 7'd4;  end
      if (lb[1])      begin vr = 7'd48; vg = 7'd48; vb = 7'd48; end
      if (plane) begin vr = 7'd48; vg = 7'd48; vb = 7'd48; end
    end

    // cinta con los colores de la bandera
    if (pix_y >= 10'd440) begin
      if (pix_y < 10'd446)      begin vr = 7'd46; vg = 7'd40; vb = 7'd0; end
      else if (pix_y < 10'd474) begin vr = 7'd0;  vg = 7'd10; vb = 7'd28; end
      else                      begin vr = 7'd42; vg = 7'd4;  vb = 7'd6; end
      if (tt == 2'd1) begin vr = 7'd48; vg = 7'd44; vb = 7'd8; end
      if (tt == 2'd2) begin vr = 7'd48; vg = 7'd48; vb = 7'd48; end
    end
  end

  reg [3:0] bayer;
  always @*
    case ({pix_y[1:0], pix_x[1:0]})
      4'h0: bayer = 0;  4'h1: bayer = 8;  4'h2: bayer = 2;  4'h3: bayer = 10;
      4'h4: bayer = 12; 4'h5: bayer = 4;  4'h6: bayer = 14; 4'h7: bayer = 6;
      4'h8: bayer = 3;  4'h9: bayer = 11; 4'hA: bayer = 1;  4'hB: bayer = 9;
      4'hC: bayer = 15; 4'hD: bayer = 7;  4'hE: bayer = 13; default: bayer = 5;
    endcase

  function [1:0] dith(input [6:0] vv, input [3:0] b);
    reg [7:0] s;
    begin s = vv + b; dith = (s[7:4] > 4'd3) ? 2'd3 : s[5:4]; end
  endfunction

  assign R = video_active ? dith(vr, bayer) : 2'b00;
  assign G = video_active ? dith(vg, bayer) : 2'b00;
  assign B = video_active ? dith(vb, bayer) : 2'b00;

