  wire [9:0] pdx = (mx > {2'b0, PAN_X}) ? mx - {2'b0, PAN_X} : {2'b0, PAN_X} - mx;
  wire [9:0] pdy = (my > pin_hy) ? my - pin_hy : pin_hy - my;
  wire [9:0] pr2 = (pdx < 10'd8 && pdy < 10'd8) ? pdx * pdx + pdy * pdy : 10'd999;
  wire pin_head = (pr2 <= 10'd25);
  wire pin_hole = (pr2 <= 10'd4);
  wire pin_tip  = (my >= pin_hy) && (my <= pin_ty) && ({pdx, 1'b0} + 10'd1 <= pin_ty - my);
  wire pin_gnd  = (pdx < 10'd6) && (my == {1'b0, PAN_Y} + 10'd1) && (bounce < 5'd5);

  // Loja: punto que pulsa y ondas al llegar el avión
  wire [9:0] jdx = (mx > {2'b0, LOJ_X}) ? mx - {2'b0, LOJ_X} : {2'b0, LOJ_X} - mx;
  wire [9:0] jdy = (my > {1'b0, LOJ_Y}) ? my - {1'b0, LOJ_Y} : {1'b0, LOJ_Y} - my;
  wire [13:0] jr2 = (jdx < 10'd64 && jdy < 10'd64) ? jdx[5:0] * jdx[5:0] + jdy[5:0] * jdy[5:0] : 14'h3FFF;
  wire [5:0]  rr  = {loopf[4:0], 1'b0};      // ondas al doble de velocidad
  wire [5:0]  rr2 = rr + 6'd32;
  wire ring = !flying && in_map && (
               (jr2 + {rr, 1'b0} >= {8'b0, rr} * rr  && jr2 <= {8'b0, rr} * rr + {rr, 1'b0} + 14'd1) ||
               (jr2 + {rr2, 1'b0} >= {8'b0, rr2} * rr2 && jr2 <= {8'b0, rr2} * rr2 + {rr2, 1'b0} + 14'd1));
  wire loja_dot  = (jr2 <= 14'd9);
  wire loja_glow = (jr2 <= (frame[3] ? 14'd30 : 14'd20));

  // etiquetas del mapa (texto + contorno)
  function [1:0] lab_px(input [9:0] x, input [9:0] y, input [9:0] x0, input [9:0] y0,
                        input [7:0] w, input [4:0] h, input [255:0] row);
    reg [9:0] lxx, lyy;
    begin
      lxx = x - x0; lyy = y - y0;
      lab_px = (x >= x0 && y >= y0 && lxx < {2'b0, w} && lyy < {5'b0, h}) ? row[{lxx[6:0], 1'b0} +: 2] : 2'd0;
    end
  endfunction
  wire [1:0] lb_pan  = lab_px(mx, my, 10'd14,  10'd1,   LAB_PAN_W,  LAB_PAN_H,  lab_pan(my[4:0] - 5'd1));
  wire [1:0] lb_aqui = lab_px(mx, my, 10'd116, 10'd38,  LAB_AQUI_W, LAB_AQUI_H, lab_aqui(my[4:0] - 5'd6));
  wire [1:0] lb_ecu  = lab_px(mx, my, 10'd100, 10'd282, LAB_ECU_W,  LAB_ECU_H,  lab_ecu(my[4:0] - 5'd26));
  wire [1:0] lb_loja = lab_px(mx, my, 10'd122, 10'd375, LAB_LOJA_W, LAB_LOJA_H, lab_loja(my[4:0] - 5'd23));
  wire [1:0] lb = lb_pan | lb_aqui | lb_ecu | lb_loja;

