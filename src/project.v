  reg [6:0] vr, vg, vb;
  always @* begin
    // fondo UNL y sombra larga
    if (shadow) begin vr = 7'd39; vg = 7'd9; vb = 7'd11; end
    else        begin vr = 7'd42; vg = 7'd9; vb = 7'd11; end
    // letras del logo
    case (alpha)
